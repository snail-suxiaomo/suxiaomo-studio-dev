// 把"预设 + 用户历史"合并为一个去重、有序的标签来源
export function mergeOptions(presets, history) {
  const seen = new Set()
  const out = []
  const pushAll = (arr) => {
    for (const x of arr || []) {
      const v = String(x || '').trim()
      if (v && !seen.has(v)) {
        seen.add(v)
        out.push(v)
      }
    }
  }
  pushAll(presets)
  pushAll(history)
  return out
}
